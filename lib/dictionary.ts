// Function to look up a word
export function lookupWord(
  word: string,
  direction: "es-en" | "en-es" = "es-en",
): { translation: string; pronunciation?: string; partOfSpeech?: string } | null {
  const cleanWord = word
    .toLowerCase()
    .replace(/[.,!?¿¡;:'"]/g, "")
    .trim()

  if (direction === "es-en") {
    return spanishToEnglish[cleanWord] || null
  } else {
    return englishToSpanish[cleanWord] || null
  }
}

// Function to detect language (simple heuristic)
export function detectLanguage(text: string): "es" | "en" {
  const spanishIndicators = ["á", "é", "í", "ó", "ú", "ñ", "¿", "¡"]
  const spanishWords = [
    "el",
    "la",
    "los",
    "las",
    "es",
    "está",
    "son",
    "están",
    "yo",
    "tú",
    "él",
    "ella",
    "nosotros",
    "ellos",
  ]

  // Check for Spanish characters
  for (const char of spanishIndicators) {
    if (text.includes(char)) return "es"
  }

  // Check for common Spanish words
  const words = text.toLowerCase().split(/\s+/)
  let spanishCount = 0
  let englishCount = 0

  for (const word of words) {
    const cleanWord = word.replace(/[.,!?¿¡;:'"]/g, "")
    if (spanishWords.includes(cleanWord) || spanishToEnglish[cleanWord]) {
      spanishCount++
    }
    if (englishToSpanish[cleanWord]) {
      englishCount++
    }
  }

  return spanishCount >= englishCount ? "es" : "en"
}
